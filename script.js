/* SHOW QUESTION */

function showQuestion(){

    answered = false;

    const question =
        quizQuestions[quizIndex];


    document.getElementById(
        "quizProgress"
    ).textContent =
        `${quizIndex + 1} / ${quizQuestions.length}`;


    document.getElementById(
        "progressFill"
    ).style.width =
        `${((quizIndex + 1) / quizQuestions.length) * 100}%`;


    const content =
        document.getElementById("quizContent");


    content.innerHTML = `

        <div class="question-number">
            QUESTION ${quizIndex + 1}
        </div>

        <div class="question-text">
            ${question.q}
        </div>

        <div class="quiz-options">

            ${question.options.map(
                (option,index) => `

                    <button
                        class="quiz-option"
                        data-option="${index}"
                    >
                        ${String.fromCharCode(65 + index)}.
                        ${option}
                    </button>

                `
            ).join("")}

        </div>

    `;


    document
        .querySelectorAll(".quiz-option")
        .forEach(button => {

            button.addEventListener(
                "click",
                () => {

                    answerQuestion(
                        button,
                        question
                    );

                }
            );

        });

}


/* ANSWER */

function answerQuestion(button,question){

    if(answered) return;

    answered = true;


    const selected =
        button.textContent
        .replace(/^[A-D]\.\s*/,"")
        .trim();


    const buttons =
        document.querySelectorAll(
            ".quiz-option"
        );


    buttons.forEach(option => {

        option.disabled = true;


        const value =
            option.textContent
            .replace(/^[A-D]\.\s*/,"")
            .trim();


        if(value === question.answer){

            option.classList.add("correct");

        }

    });


    if(selected === question.answer){

        quizScore++;

        button.classList.add("correct");

    }else{

        button.classList.add("wrong");

    }


    const next =
        document.createElement("button");


    next.className = "quiz-next";

    next.textContent =
        quizIndex === quizQuestions.length - 1
        ? "Finish Quiz"
        : "Next Question →";


    next.addEventListener(
        "click",
        () => {

            if(
                quizIndex ===
                quizQuestions.length - 1
            ){

                showQuizResult();

            }else{

                quizIndex++;

                showQuestion();

            }

        }
    );


    document
        .getElementById("quizContent")
        .appendChild(next);

}


/* RESULT */

function showQuizResult(){

    const total =
        quizQuestions.length;


    let message;


    if(quizScore === total){

        message =
            "Perfect score! You know this country extremely well.";

    }else if(quizScore >= 8){

        message =
            "Excellent work! You know a lot about this country.";

    }else if(quizScore >= 5){

        message =
            "Good effort! Explore the country details and try again.";

    }else{

        message =
            "Keep exploring! Read the country summary and try the quiz again.";

    }


    document.getElementById(
        "quizContent"
    ).innerHTML = `

        <div class="quiz-result">

            <div class="quiz-result-icon">
                ${quizScore === total ? "🏆" : "🌍"}
            </div>

            <h2>
                ${quizScore} / ${total}
            </h2>

            <p>
                ${message}
            </p>

            <button
                class="restart-btn"
                id="restartQuiz"
            >
                🔄 Try Again
            </button>

        </div>

    `;


    document.getElementById(
        "restartQuiz"
    ).addEventListener(
        "click",
        () => {

            quizIndex = 0;

            quizScore = 0;

            showQuestion();

        }
    );

}


